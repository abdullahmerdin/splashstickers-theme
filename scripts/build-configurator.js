'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourceDirectory = path.join(root, 'assets', 'sticker-configurator');
const bundlePath = path.join(root, 'assets', 'sticker-configurator.js');

const moduleOrder = [
  'utils.js',
  'snap-engine.js',
  'collision-engine.js',
  'canvas-renderer.js',
  'item-manager.js',
  'selection-manager.js',
  'history-manager.js',
  'alignment-engine.js',
  'mobile-handler.js',
  'modal-manager.js',
  'export-manager.js',
  'keyboard-manager.js',
  'clipboard-manager.js',
  'cart-manager.js',
  'price-manager.js',
  'interaction-manager.js',
];

const generatedBanner = [
  '/* @generated by scripts/build-configurator.js; do not edit manually. */',
  '/* Source modules: assets/sticker-configurator/*.js */',
].join('\n');

function normalize(source) {
  return source.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim();
}

function read(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), 'utf8');
}

function getExpectedFiles() {
  return fs.readdirSync(sourceDirectory)
    .filter((file) => file.endsWith('.js'))
    .sort();
}

function buildBundle() {
  const sourceFiles = getExpectedFiles();
  const expectedSourceFiles = [...moduleOrder, 'entry.js'].sort();
  const unexpectedFiles = sourceFiles.filter((file) => !expectedSourceFiles.includes(file));
  const missingFiles = expectedSourceFiles.filter((file) => !sourceFiles.includes(file));
  const errors = [];

  if (unexpectedFiles.length) {
    errors.push('Unexpected configurator source files: ' + unexpectedFiles.join(', '));
  }
  if (missingFiles.length) {
    errors.push('Missing configurator source files: ' + missingFiles.join(', '));
  }
  if (errors.length) throw new Error(errors.join('\n'));

  const parts = [
    generatedBanner,
    ...moduleOrder.map((file) => normalize(read(path.join('assets', 'sticker-configurator', file)))),
    normalize(read(path.join('assets', 'sticker-configurator', 'entry.js'))),
  ];

  return parts.join('\n\n') + '\n';
}

const expected = buildBundle();
const current = fs.existsSync(bundlePath) ? fs.readFileSync(bundlePath, 'utf8') : '';

if (process.argv.includes('--check')) {
  if (normalize(current) !== normalize(expected)) {
    console.error('Configurator bundle is out of date. Run: npm.cmd run build:configurator');
    process.exitCode = 1;
  } else {
    console.log('Configurator bundle is deterministic and up to date.');
  }
} else {
  fs.writeFileSync(bundlePath, expected, 'utf8');
  console.log('Built assets/sticker-configurator.js from ' + moduleOrder.length + ' source modules and entry.js.');
}
