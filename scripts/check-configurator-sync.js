const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const generatedBanner = '/* @generated by scripts/build-configurator.js; do not edit manually. */';
const normalize = (value) => value.replace(/\r\n/g, '\n').trim();
const bundle = normalize(fs.readFileSync(path.join(root, 'assets', 'sticker-configurator.js'), 'utf8'));
if (!bundle.startsWith(generatedBanner)) {
  console.error('Configurator bundle is missing its generated banner.');
  process.exitCode = 1;
}
const modulesDirectory = path.join(root, 'assets', 'sticker-configurator');
const modules = fs.readdirSync(modulesDirectory)
  .filter((file) => file.endsWith('.js') && file !== 'entry.js');
const entry = normalize(fs.readFileSync(path.join(modulesDirectory, 'entry.js'), 'utf8'));
const missing = modules.filter((file) => {
  const moduleSource = normalize(fs.readFileSync(path.join(modulesDirectory, file), 'utf8'));
  return !bundle.includes(moduleSource);
});

if (missing.length || !bundle.includes(entry)) {
  const missingSources = missing.concat(!bundle.includes(entry) ? ['entry.js'] : []);
  console.error('Configurator bundle is out of sync with: ' + missingSources.join(', '));
  process.exitCode = 1;
} else {
  console.log('Configurator bundle contains all ' + modules.length + ' source modules and entry.js.');
}
