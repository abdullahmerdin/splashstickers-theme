const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const generatedBanner = '/* @generated by scripts/build-configurator.js; do not edit manually. */';
const normalize = (value) => value.replace(/\r\n/g, '\n').trim();
const bundle = normalize(fs.readFileSync(path.join(root, 'assets', 'sticker-configurator.js'), 'utf8'));
const sourceDirectory = path.join(root, 'assets', 'sticker-configurator');
const sourceManifestMatch = bundle.match(/^\/\* Source manifest \(sha256\): (.+) \*\/$/m);
const sourceManifest = sourceManifestMatch
  ? new Map(sourceManifestMatch[1].split(' | ').map((entry) => entry.split(':')))
  : new Map();

if (!bundle.startsWith(generatedBanner)) {
  console.error('Configurator bundle is missing its generated banner.');
  process.exitCode = 1;
}
if (!sourceManifestMatch) {
  console.error('Configurator bundle is missing its source manifest.');
}

const sourceFiles = fs.readdirSync(sourceDirectory)
  .filter((file) => file.endsWith('.js'))
  .sort();
const missing = [];
const stale = [];
sourceFiles.forEach((file) => {
  const source = normalize(fs.readFileSync(path.join(sourceDirectory, file), 'utf8'));
  const expectedHash = crypto.createHash('sha256').update(source, 'utf8').digest('hex');
  if (sourceManifest.get(file) !== expectedHash) stale.push(file);
  if (!bundle.includes(source)) missing.push(file);
});

if (missing.length || stale.length) {
  const issues = [];
  if (missing.length) issues.push('missing sources: ' + missing.join(', '));
  if (stale.length) issues.push('stale source manifest: ' + stale.join(', '));
  console.error('Configurator bundle is out of sync (' + issues.join('; ') + ').');
  process.exitCode = 1;
} else {
  console.log('Configurator bundle contains all ' + sourceFiles.length + ' source files with matching SHA-256 entries.');
}
